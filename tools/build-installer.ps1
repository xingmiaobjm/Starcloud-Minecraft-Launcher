# Starcloud Minecraft Launcher - one-shot packaging (portable zip + NSIS installer)
#
# ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less .ps1 files as ANSI,
# same convention as tools\gen-wallpapers.ps1 / gen-app-icon.ps1.
#
# Usage (from anywhere):
#   powershell -ExecutionPolicy Bypass -File tools\build-installer.ps1
#   powershell -ExecutionPolicy Bypass -File tools\build-installer.ps1 -SkipPublish
#   powershell -ExecutionPolicy Bypass -File tools\build-installer.ps1 ^
#       -NotesFile docs\releases\0.3.1-notes.txt -NotesEnFile docs\releases\0.3.1-notes.en.txt
#
# Produces (in releases\, which is git-ignored):
#   Starcloud Minecraft Launcher_<version>_x64-portable-<stamp>.zip
#   Starcloud Minecraft Launcher_<version>_x64-setup-<stamp>.exe
#   latest.json                        (update manifest; upload together with the two artifacts)
#
# The launcher is unpackaged + self-contained (WindowsPackageType=None), so
# "packaging" is: publish -> zip the folder -> wrap the same folder in NSIS.

[CmdletBinding()]
param(
    # Reuse the previous publish output (fast loop when only installer.nsi changed).
    [switch]$SkipPublish,
    # Release notes baked into latest.json, shown by the launcher's update dialog.
    # Pass *file paths* (e.g. docs\releases\0.3.1-notes.txt), not inline text:
    # this script is BOM-less and Windows PowerShell 5.1 reads those as ANSI, so
    # CJK typed inline would come out as mojibake. Files are read as UTF-8.
    [string]$NotesFile = '',
    [string]$NotesEnFile = ''
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root      = Split-Path -Parent $PSScriptRoot
$appCsproj = Join-Path $root 'dotnet\src\Starcloud.App\Starcloud.App.csproj'
$nsi       = Join-Path $PSScriptRoot 'installer.nsi'
$icon      = Join-Path $root 'dotnet\src\Starcloud.App\Assets\AppIcon.ico'
$staging   = Join-Path $env:TEMP 'starcloud-publish'
$outDir    = Join-Path $root 'releases'

# --- version: single source of truth is <Version> in Starcloud.App.csproj ---
[xml]$proj = Get-Content -LiteralPath $appCsproj
$version = @($proj.Project.PropertyGroup.Version | Where-Object { $_ }) | Select-Object -First 1
if (-not $version) { throw "no <Version> element in $appCsproj" }
$version = $version.Trim()

# --- icon: placeholder artwork generated by tools\gen-app-icon.ps1 ---
if (-not (Test-Path -LiteralPath $icon)) {
    throw "missing $icon - run tools\gen-app-icon.ps1 first"
}

# --- makensis: PATH first, then the NSIS bundled with the old Tauri toolchain ---
$makensis = $null
$cmd = Get-Command makensis.exe -ErrorAction SilentlyContinue
if ($cmd) { $makensis = $cmd.Source }
if (-not $makensis) {
    $candidate = Join-Path $env:LOCALAPPDATA 'tauri\NSIS\makensis.exe'
    if (Test-Path -LiteralPath $candidate) { $makensis = $candidate }
}
if (-not $makensis) { throw "makensis.exe not found - install it with: winget install NSIS.NSIS" }

# --- 1. publish (self-contained, win-x64) ---
if ($SkipPublish) {
    Write-Host "[1/5] publish skipped (-SkipPublish)"
} else {
    Write-Host "[1/5] dotnet publish -c Release -o $staging"
    if (Test-Path -LiteralPath $staging) { Remove-Item -LiteralPath $staging -Recurse -Force }
    & dotnet publish $appCsproj -c Release -o $staging -v q -nologo
    if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed with exit code $LASTEXITCODE" }
}

$mainExe = Join-Path $staging 'Starcloud.App.exe'
if (-not (Test-Path -LiteralPath $mainExe)) { throw "publish output has no Starcloud.App.exe: $staging" }
$files = Get-ChildItem -LiteralPath $staging -Recurse -File
$sizeMb = [math]::Round((($files | Measure-Object -Property Length -Sum).Sum / 1MB), 1)
Write-Host "      $($files.Count) files, $sizeMb MB in staging"

# --- 1b. compliance guard: third-party MP core must NOT ship in the package ---
# The Terracotta | 陶瓦联机 core is AGPL-3.0-or-later with an aggregation exception:
# we may download and run the official release, but we must not redistribute it.
# So the core is fetched by the launcher at runtime (first use) into
# %APPDATA%\starcloud-launcher\multiplayer\core - never into our zip/setup.
# This guard fails the build if a core ever leaks into the publish output
# (e.g. someone drops it into Assets\ or globs it from the csproj).
$forbiddenInPackage = @('terracotta', 'easytier', 'multiplayer\core', 'multiplayer/core')
$leaks = @()
foreach ($f in $files) {
    $rel = $f.FullName.Substring($staging.Length).TrimStart('\')
    $lower = $rel.ToLowerInvariant()
    foreach ($needle in $forbiddenInPackage) {
        if ($lower.Contains($needle)) { $leaks += $rel; break }
    }
}
if ($leaks.Count -gt 0) {
    throw ("refusing to package: third-party multiplayer core found in publish output: " +
        ($leaks -join ', ') +
        " - the core must be downloaded by the launcher at runtime, remove it from Assets/ or the csproj")
}
Write-Host "      compliance: no bundled multiplayer core"

# --- 2. portable zip ---
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$base  = "Starcloud Minecraft Launcher_${version}_x64"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
$zipPath = Join-Path $outDir "$base-portable-$stamp.zip"
Write-Host "[2/5] zip      -> $(Split-Path -Leaf $zipPath)"
Add-Type -AssemblyName System.IO.Compression.FileSystem
[System.IO.Compression.ZipFile]::CreateFromDirectory(
    $staging, $zipPath, [System.IO.Compression.CompressionLevel]::Optimal, $false)

# --- 3. NSIS installer ---
# /INPUTCHARSET UTF8 is required: installer.nsi is UTF-8 without BOM and NSIS 3
# otherwise reads it as ANSI (Chinese strings turn into mojibake).
$setupPath = Join-Path $outDir "$base-setup-$stamp.exe"
Write-Host "[3/5] makensis -> $(Split-Path -Leaf $setupPath)"
& $makensis /V2 /INPUTCHARSET UTF8 `
    "/DPRODUCT_VERSION=$version" `
    "/DPRODUCT_VERSION4=$($version).0" `
    "/DSRCDIR=$($staging.TrimEnd('\'))" `
    "/DOUTFILE=$setupPath" `
    "/DAPPICON=$icon" `
    $nsi
if ($LASTEXITCODE -ne 0) { throw "makensis failed with exit code $LASTEXITCODE" }

# --- 4. update manifest (latest.json) ---
# Consumed by the launcher's self-update (SelfUpdateService): "file" is a bare
# file name resolved relative to the manifest URL, so uploading = copying these
# three files into the same directory on the server. Fill "notes" by hand.
Write-Host "[4/5] manifest -> releases\latest.json"
function Get-ArtifactInfo([string]$path) {
    @{ file   = [IO.Path]::GetFileName($path)
       sha256 = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
       size   = (Get-Item -LiteralPath $path).Length }
}

# Notes arrive as UTF-8 files (see the -NotesFile parameter comment).
function Read-Notes([string]$path) {
    if ([string]::IsNullOrWhiteSpace($path)) { return '' }
    if (-not (Test-Path -LiteralPath $path)) { throw "notes file not found: $path" }
    return (Get-Content -LiteralPath $path -Raw -Encoding UTF8).Trim()
}

$manifestNotes = Read-Notes $NotesFile
$manifestNotesEn = Read-Notes $NotesEnFile
if ($manifestNotesEn -eq '') { $manifestNotesEn = $null }

$manifest = [ordered]@{
    version      = $version
    notes        = $manifestNotes
    notes_en     = $manifestNotesEn
    published_at = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
    setup        = Get-ArtifactInfo $setupPath
    portable     = Get-ArtifactInfo $zipPath
}
$manifestPath = Join-Path $outDir 'latest.json'
# WriteAllText + UTF8Encoding($false) = UTF-8 WITHOUT BOM. Never go back to
# Set-Content -Encoding UTF8 here: under Windows PowerShell 5.1 that writes a BOM,
# and the launcher parses the manifest body as a string (leading U+FEFF = invalid JSON).
$json = $manifest | ConvertTo-Json -Depth 4
[IO.File]::WriteAllText($manifestPath, $json, (New-Object System.Text.UTF8Encoding($false)))

# --- 5. summary ---
Write-Host "[5/5] done"
foreach ($p in @($zipPath, $setupPath, $manifestPath)) {
    if (-not (Test-Path -LiteralPath $p)) { throw "expected artifact missing: $p" }
    $mb = [math]::Round(((Get-Item -LiteralPath $p).Length / 1MB), 1)
    Write-Host "      $([System.IO.Path]::GetFileName($p))  ($mb MB)"
}
